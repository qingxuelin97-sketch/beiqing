export const getPlenaryById = (id: string): Plenary | undefined =>
  plenaries.find((p) => p.id === id);

export const getPlenariesByCongress = (congressOrdinal: number): Plenary[] =>
  plenaries
    .filter((p) => p.congressOrdinal === congressOrdinal)
    .sort((a, b) => a.ordinal - b.ordinal);

export const getCongressOrdinals = (): number[] => {
  const set = new Set<number>();
  plenaries.forEach((p) => set.add(p.congressOrdinal));
  return Array.from(set).sort((a, b) => a - b);
};
